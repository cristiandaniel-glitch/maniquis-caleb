BEGIN;

-- Mantiene updated_at de forma uniforme en las tablas que se pueden editar.
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    slug TEXT NOT NULL UNIQUE,
    description TEXT,
    icon TEXT NOT NULL DEFAULT 'tag',
    display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES public.categories(id) ON DELETE RESTRICT,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    sku TEXT UNIQUE,
    description TEXT NOT NULL,
    material TEXT,
    color TEXT,
    dimensions TEXT,
    price NUMERIC(12, 2) NOT NULL DEFAULT 0.00 CHECK (price >= 0),
    stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    image_url TEXT NOT NULL,
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Libro de Reclamaciones. No se vincula al producto para conservar la evidencia
-- histórica aunque el producto cambie o se desactive posteriormente.
CREATE TABLE IF NOT EXISTS public.claims_book (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_code TEXT NOT NULL UNIQUE,
    claim_type TEXT NOT NULL CHECK (claim_type IN ('Reclamo', 'Queja')),

    full_name TEXT NOT NULL,
    doc_type TEXT NOT NULL CHECK (doc_type IN ('DNI', 'CE', 'Pasaporte', 'RUC')),
    doc_number TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT NOT NULL,
    address TEXT NOT NULL,
    is_minor BOOLEAN NOT NULL DEFAULT FALSE,
    guardian_name TEXT,

    contracted_good TEXT NOT NULL CHECK (contracted_good IN ('Producto', 'Servicio')),
    amount_claimed NUMERIC(12, 2) NOT NULL DEFAULT 0.00 CHECK (amount_claimed >= 0),
    good_description TEXT NOT NULL,
    claim_description TEXT NOT NULL,
    consumer_request TEXT NOT NULL,

    status TEXT NOT NULL DEFAULT 'Pendiente'
        CHECK (status IN ('Pendiente', 'En Proceso', 'Atendido', 'Cerrado')),
    admin_response TEXT,
    response_date TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CHECK (NOT is_minor OR NULLIF(btrim(guardian_name), '') IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS public.contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT,
    subject TEXT NOT NULL,
    message TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'unread'
        CHECK (status IN ('unread', 'read', 'archived')),
    ip_address INET,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.subscribers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'unsubscribed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.security_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action TEXT NOT NULL,
    detail TEXT,
    ip_address INET,
    user_agent TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Estas tablas hoy se crean desde Python. Se declaran aquí para que el esquema
-- de producción sea completo y se pueda versionar mediante migraciones.
CREATE TABLE IF NOT EXISTS public.reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    boutique TEXT NOT NULL,
    city TEXT NOT NULL DEFAULT 'Cusco',
    product_model TEXT,
    rating SMALLINT NOT NULL DEFAULT 5 CHECK (rating BETWEEN 1 AND 5),
    comment TEXT NOT NULL,
    is_verified BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.login_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip_address INET NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Índices alineados a las consultas actuales del backend.
CREATE INDEX IF NOT EXISTS idx_categories_active_display_order
    ON public.categories (is_active, display_order, name);
CREATE INDEX IF NOT EXISTS idx_products_active_featured_created_at
    ON public.products (is_active, is_featured DESC, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_products_active_category_featured_created_at
    ON public.products (is_active, category_id, is_featured DESC, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_products_category_active
    ON public.products (category_id, is_active);
CREATE INDEX IF NOT EXISTS idx_claims_status_created_at
    ON public.claims_book (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_claims_created_at
    ON public.claims_book (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_messages_status_created_at
    ON public.contact_messages (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_subscribers_status_created_at
    ON public.subscribers (status, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_subscribers_email_lower
    ON public.subscribers (lower(email));
CREATE INDEX IF NOT EXISTS idx_security_logs_created_at
    ON public.security_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_reviews_created_at
    ON public.reviews (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_login_attempts_ip_created_at
    ON public.login_attempts (ip_address, created_at DESC);

DROP TRIGGER IF EXISTS categories_set_updated_at ON public.categories;
CREATE TRIGGER categories_set_updated_at
BEFORE UPDATE ON public.categories
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS products_set_updated_at ON public.products;
CREATE TRIGGER products_set_updated_at
BEFORE UPDATE ON public.products
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS claims_book_set_updated_at ON public.claims_book;
CREATE TRIGGER claims_book_set_updated_at
BEFORE UPDATE ON public.claims_book
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Las tablas en public pueden estar expuestas por la Data API de Supabase.
-- Sin políticas, anon y authenticated no tienen acceso; el backend servidor
-- seguirá conectándose con su credencial privada. No expongas esa credencial
-- ni la service_role key al frontend.
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.claims_book ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contact_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.subscribers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.security_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.login_attempts ENABLE ROW LEVEL SECURITY;

COMMIT;
